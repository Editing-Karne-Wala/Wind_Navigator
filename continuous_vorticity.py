"""
WIND_NAVIGATOR -- Phase 31: Continuous Spatial Vorticity
========================================================
Resolving Gap C4: "Binary in_bif flag loses spatial information."

Instead of a binary True/False flag for bifurcation, we use the continuous 
velocity fields generated by Phase 29's true D2Q9 LBM engine to calculate
Discrete Integer Vorticity.

Vorticity (omega) = dv/dx - du/dy

This yields a continuous integer scalar. A drone 2m from the edge of a 
vortex sees a low score (e.g., 50), while a drone in the core sees a 
massive score (e.g., 2500). A* pathfinders can now softly "surf" or
avoid fields based on quantitative risk, rather than binary panic.
"""

from lbm_d2q9_core import IntegerLBM
import time

def compute_vorticity(u_field, v_field, W, H):
    """
    Computes 2D discrete vorticity using central differences.
    Returns a 2D array of continuous integer vorticity scalars.
    """
    omega = [[0 for _ in range(W)] for _ in range(H)]
    
    for y in range(1, H - 1):
        for x in range(1, W - 1):
            # Finite difference dv/dx
            dv_dx = (v_field[y][x+1] - v_field[y][x-1]) // 2
            # Finite difference du/dy
            du_dy = (u_field[y+1][x] - u_field[y-1][x]) // 2
            
            # 2D Vorticity magnitude (absolute value to show sheer severity)
            omega[y][x] = abs(dv_dx - du_dy)
            
    return omega

def demonstrate_continuous_gradient():
    print("="*60)
    print("Phase 31: Continuous Spatial Vorticity Mapping")
    print("="*60)
    
    W, H = 20, 20
    terrain = [[0 for _ in range(W)] for _ in range(H)]
    # Building block blocking West-East wind
    for y in range(8, 12):
        for x in range(8, 10):
            terrain[y][x] = 1
            
    lbm = IntegerLBM(W, H, terrain)
    
    # Warm up LBM to generate steady state vortex behind the building
    for _ in range(150):
        lbm.simulate_step(tau_omega=120, inlet_u=8000, inlet_v=1000)
    
    u_map, v_map = lbm.get_velocity_field()
    vorticity_map = compute_vorticity(u_map, v_map, W, H)
    
    print("Continuous Vorticity Field behind the structure [x=10]:")
    print("(Notice the smooth numerical gradient tracking distance from the core)")
    
    for y in range(5, 15):
        omega_val = vorticity_map[y][10]
        # Visual representation: High numbers get bigger ASCII bars
        bar_len = min(20, omega_val // 20)
        bar = "#" * bar_len
        bldg = "|XX|" if (8 <= y < 12) else "    "
        print(f" Y={y:2d} {bldg} ->  w: {omega_val:4d} | {bar}")
        
    print("\nGap C4 Closed: The drone now evaluates continuous topological risk")
    print("instead of binary True/False flags. Closer to the core = exponentially")
    print("higher vorticity penalty for the A* cost function.")
    print("="*60)

if __name__ == "__main__":
    demonstrate_continuous_gradient()
